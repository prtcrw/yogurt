import { _electron as electron, expect, test } from '@playwright/test'
import { existsSync, mkdtempSync, mkdirSync, readFileSync, realpathSync, rmSync, utimesSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
const main = join(import.meta.dirname, '../out/main/index.js')
const launch = (profile: string) => electron.launch({ args: [main], env: { ...process.env, YOGURT_FAKE: '1', YOGURT_USER_DATA: profile } })

test('model and cache paths validate, persist and become active on restart', async () => {
  const root = realpathSync(mkdtempSync(join(tmpdir(), 'yogurt-settings-ui-'))), profile = join(root, 'Profile'), models = join(root, 'Models'), work = join(root, 'Cache')
  mkdirSync(models); mkdirSync(work)
  const speech = join(models, 'speech.bin'), summary = join(models, 'summary.gguf'); const header = Buffer.alloc(8); header.writeUInt32LE(0x67676d6c)
  writeFileSync(speech, header); writeFileSync(summary, 'GGUFtest')
  let app = await launch(profile)
  try {
    let page = await app.firstWindow(); await expect(page.getByTestId('home')).toBeVisible({ timeout: 20000 })
    await app.evaluate(() => (globalThis as any).__fake__.go('/settings'))
    await page.getByText('Models, folders & tools', { exact: true }).click()
    await page.getByLabel('Speech model file', { exact: true }).fill(summary)
    await page.getByRole('button', { name: 'Save model and folder settings' }).click()
    await expect(page.getByRole('alert')).toContainText('Whisper GGML')
    await page.getByLabel('Speech model file', { exact: true }).fill(speech)
    await page.getByLabel('Local summary model file', { exact: true }).fill(summary)
    await page.getByLabel('Model download folder', { exact: true }).fill(models)
    await page.getByLabel('Processing cache folder', { exact: true }).fill(work)
    await page.getByRole('button', { name: 'Save model and folder settings' }).click()
    await expect(page.getByText('Settings saved.', { exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: 'Restart Yogurt Projects' })).toBeVisible()
    let state = await page.evaluate(() => window.yogurt.runtime.state())
    expect(state.saved.speechModel).toBe(speech); expect(state.restartRequired).toBe(true); expect(state.effective.workDirectory).not.toBe(work)
    await app.close(); app = await launch(profile); page = await app.firstWindow()
    await expect(page.getByTestId('app-shell')).toBeVisible({ timeout: 20000 })
    state = await page.evaluate(() => window.yogurt.runtime.state())
    expect(state.restartRequired).toBe(false); expect(state.effective.summaryModel).toBe(summary); expect(state.effective.workDirectory).toBe(work)
    expect(readFileSync(summary, 'utf8')).toBe('GGUFtest')
  } finally { await app.close(); rmSync(root, { recursive: true, force: true }) }
})

test('input-folder checks ask first, skip files without changing them and import only after approval', async () => {
  const root = realpathSync(mkdtempSync(join(tmpdir(), 'yogurt-inbox-ui-'))), profile = join(root, 'Profile'), vault = join(root, 'Vault'), input = join(root, 'Incoming')
  mkdirSync(vault); mkdirSync(input); mkdirSync(join(vault, 'Exports'))
  const source = join(input, 'meeting.wav'); writeFileSync(source, 'original recording'); const old = new Date(Date.now() - 20000); utimesSync(source, old, old)
  const app = await launch(profile)
  try {
    const page = await app.firstWindow(); await expect(page.getByTestId('home')).toBeVisible({ timeout: 20000 })
    await app.evaluate(() => (globalThis as any).__fake__.go('/projects'))
    await page.getByLabel('Name', { exact: true }).fill('Test project')
    await app.evaluate(({ dialog }, path) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [path] }) }, vault)
    await page.getByRole('button', { name: 'Choose vault folder', exact: true }).click()
    await app.evaluate(({ dialog }, path) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [path] }) }, join(vault, 'Exports'))
    await page.getByRole('button', { name: 'Browse output folder…' }).click()
    await expect(page.getByLabel('Meeting output subfolder')).toHaveValue('Exports')
    await page.getByLabel('Recording input folder').fill(input)
    await page.getByLabel('Check input folder and ask before importing').check()
    await page.getByLabel('Imported speech language').selectOption('th')
    await page.getByLabel('Suggest a follow-up from meeting context').uncheck()
    await page.screenshot({ path: join(tmpdir(), 'yogurt-projects-settings.png') })
    await page.getByRole('button', { name: 'Create project', exact: true }).click()
    await expect.poll(() => page.evaluate(async () => (await window.yogurt.projects.state()).projects.length)).toBe(1)
    await expect.poll(() => page.evaluate(async () => { await window.yogurt.projects.checkInbox(); return (await window.yogurt.projects.state()).inbox?.length })).toBe(1)
    let state = await page.evaluate(() => window.yogurt.projects.state()); expect(state.jobs).toHaveLength(0); expect(state.projects[0].speechLanguage).toBe('th')
    await app.evaluate(() => (globalThis as any).__fake__.go(''))
    await expect(page.getByTestId('inbox-notice')).toContainText('waiting for import approval')
    await page.getByRole('button', { name: 'Review recordings' }).click()
    await page.getByRole('button', { name: 'Skip this file' }).click()
    expect(readFileSync(source, 'utf8')).toBe('original recording'); state = await page.evaluate(() => window.yogurt.projects.state()); expect(state.jobs).toHaveLength(0)
    await page.evaluate(() => window.yogurt.projects.checkInbox()); expect((await page.evaluate(() => window.yogurt.projects.state())).inbox).toHaveLength(0)
    const second = join(input, 'another.wav'); writeFileSync(second, 'second original recording'); utimesSync(second, old, old)
    await expect.poll(() => page.evaluate(async () => { await window.yogurt.projects.checkInbox(); return (await window.yogurt.projects.state()).inbox?.length })).toBe(1)
    await page.getByRole('button', { name: 'Import recording', exact: true }).click()
    await expect.poll(() => page.evaluate(async () => (await window.yogurt.projects.state()).jobs[0]?.state)).toBe('review')
    expect(existsSync(second)).toBe(true); await expect(page.getByRole('button', { name: 'Approve speakers and summarize' })).toBeVisible()
    await page.screenshot({ path: join(tmpdir(), 'yogurt-projects-activity.png') })
    await page.getByRole('button', { name: 'Approve speakers and summarize' }).click()
    await expect.poll(() => page.evaluate(async () => (await window.yogurt.projects.state()).jobs[0]?.state)).toBe('completed')
    state = await page.evaluate(() => window.yogurt.projects.state()); expect(state.jobs).toHaveLength(1); expect(state.inbox).toHaveLength(0)
    const notes = state.jobs[0].notes!; expect(notes).toContain('/Exports/'); expect(readFileSync(notes.replace('notes.md', 'follow-up.md'), 'utf8')).toContain('disabled for this project')
    await page.screenshot({ path: join(tmpdir(), 'yogurt-settings-review.png'), fullPage: true })
  } finally { await app.close(); rmSync(root, { recursive: true, force: true }) }
})

test('first startup discovers existing models and waits for a choice before any downloads', async () => {
  const root = realpathSync(mkdtempSync(join(tmpdir(), 'yogurt-existing-ui-'))), profile = join(root, 'Profile'), models = join(profile, 'reusable-models')
  mkdirSync(models, { recursive: true })
  const speech = join(models, 'ggml-base.bin'), summary = join(models, 'meeting-model.gguf'), header = Buffer.alloc(8); header.writeUInt32LE(0x67676d6c)
  writeFileSync(speech, header); writeFileSync(summary, 'GGUFtest')
  const app = await electron.launch({ args: [main], env: { ...process.env, YOGURT_FAKE: '1', YOGURT_FAKE_MODEL_DISCOVERY: '1', YOGURT_USER_DATA: profile } })
  try {
    const page = await app.firstWindow(); await expect(page.getByTestId('model-setup')).toBeVisible()
    await expect(page.getByLabel('Existing speech model')).toHaveValue(speech)
    await expect(page.getByLabel('Existing local summary model')).toHaveValue(summary)
    expect((await page.evaluate(() => window.yogurt.setup.state())).phase).toBe('models')
    expect(existsSync(join(profile, 'models'))).toBe(false)
    await page.screenshot({ path: join(tmpdir(), 'yogurt-model-setup.png') })
    await page.getByTestId('models-continue').click()
    await expect(page.getByTestId('home')).toBeVisible({ timeout: 20000 })
    const prefs = await page.evaluate(() => window.yogurt.runtime.state())
    expect(prefs.effective.speechModel).toBe(speech); expect(prefs.effective.summaryModel).toBe(summary)
    expect(existsSync(join(profile, 'models/asr'))).toBe(false); expect(existsSync(join(profile, 'models/llm'))).toBe(false)
    expect(readFileSync(summary, 'utf8')).toBe('GGUFtest')
  } finally { await app.close(); rmSync(root, { recursive: true, force: true }) }
})
